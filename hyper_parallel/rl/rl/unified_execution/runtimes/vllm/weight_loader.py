"""Load logical HF weights into HP layouts without retaining bucket tensors."""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass
from typing import Any

import torch
from torch import nn

from rl.weight_sync.model_adapter import expert_weight_slices
from hyper_parallel.components.checkpoint.conversion_ops import ConcatenateWithSections, InterleaveQKV
from hyper_parallel.components.checkpoint.load_groups import (
    local_target_tensor,
    reject_partial_layout,
    shard_for_target,
    target_layout,
)
from hyper_parallel.core.dtensor.dtensor import distribute_tensor
from hyper_parallel.core.dtensor.layout import infer_slice_area_by_layout
from hyper_parallel.core.dtensor.placement_types import Replicate, Shard


@dataclass(frozen=True)
class _Destination:
    """A parameter or its logical-source rows derived from HP's converter."""

    name: str
    rows: torch.Tensor | None = None
    region: tuple[tuple[int, ...], tuple[int, ...]] | None = None
    local_region: tuple[slice, ...] | None = None


class LogicalWeightLoader:
    """Apply HP's reversible row mappings across a complete publication.

    Online callers must bracket all buckets with ``begin`` and ``finish``.
    Initial checkpoint iteration is a single implicit transaction. Conversion
    indices are generated by the actual HP inverse operation, so this adapter
    does not maintain a second QKV or Gate/Up permutation formula.
    """

    def __init__(self, model: nn.Module) -> None:
        """Index the model parameters and replacement-owned conversions."""
        self.parameters = dict(model.named_parameters(remove_duplicate=False))
        logical_shapes = getattr(model, "_rl_logical_parameter_shapes", {})
        self.shapes = {}
        for name, parameter in self.parameters.items():
            layout = target_layout(parameter)
            self.shapes[name] = tuple(
                logical_shapes.get(name)
                or (layout.get_global_shape(local_target_tensor(parameter).shape) if layout is not None
                    else parameter.shape)
            )
        self.destinations = {name: _Destination(name) for name in self.parameters}
        self.required: dict[int, set[str]] = {}
        self.seen: set[str] = set()
        self.active = False
        for module_name, module in model.named_modules():
            if (getattr(getattr(model, "config", None), "model_type", None) == "qwen3_moe"
                    and module_name.endswith(".mlp.experts")):
                self._add_experts(module_name, model.config)
                continue
            make_transforms = getattr(module, "make_transforms", None)
            if make_transforms is not None:
                transforms = getattr(module, "_rl_logical_weight_transforms", None)
                if transforms is None:
                    transforms = make_transforms()
                for transform in transforms:
                    self._add_transform(module_name, transform)
        if getattr(getattr(model, "config", None), "tie_word_embeddings", False):
            aliases = ("model.embed_tokens.weight", "lm_head.weight")
            existing = next((name for name in aliases if name in self.parameters), None)
            if existing is not None:
                for name in aliases:
                    self.destinations.setdefault(name, _Destination(existing))
        for name, destination in self.destinations.items():
            parameter = self.parameters[destination.name]
            self.required.setdefault(id(parameter), set()).add(name)

    def _add_experts(self, prefix: str, config: Any) -> None:
        """Invert the existing publication adapter's expert projection slices."""
        for projection in ("gate_up_proj", "down_proj"):
            name = f"{prefix}.{projection}"
            if name not in self.parameters:
                raise ValueError(f"Unified MoE requires the HP GroupedExperts parameter {name}")
            layout = target_layout(self.parameters[name])
            area = tuple((0, size) for size in self.shapes[name])
            if layout is not None:
                reject_partial_layout(name, layout)
                if any(placement.is_shard() and placement.dim != 0 for placement in layout.placements):
                    raise ValueError(
                        "Unified fused experts support EP sharding or TP replication, not expert-internal TP"
                    )
                area = infer_slice_area_by_layout(
                    layout, layout.rank_list.index(layout.mesh.rank), self.shapes[name],
                )
            self.destinations.pop(name, None)
            for entry in expert_weight_slices(name, self.shapes[name], config):
                region = (tuple(entry["starts"]), tuple(entry["shape"]))
                starts, lengths = region
                owned = area[0][0] <= starts[0] < area[0][1]
                local_region = tuple(slice(start - lower, start - lower + length)
                                     for start, length, (lower, _) in zip(starts, lengths, area)) if owned else None
                self.destinations[entry["name"]] = _Destination(name, region=region, local_region=local_region)

    def _copy_rows(self, name: str, rows: torch.Tensor, value: torch.Tensor) -> None:
        """Intersect converted global rows with the actual destination shard.

        Logical Q/K/V buckets can arrive independently. Only owned rows are
        copied, so no full fused projection or retained bucket is necessary.
        """
        parameter = self.parameters[name]
        local = local_target_tensor(parameter)
        layout = target_layout(parameter)
        if layout is not None:
            reject_partial_layout(name, layout)
            row_count = self.shapes[name][0]
            row_placements = [
                Shard(0) if placement.is_shard() and placement.dim == 0 else Replicate()
                for placement in layout.placements
            ]
            local_rows = distribute_tensor(
                torch.arange(row_count, device=value.device), layout.mesh, row_placements, src_data_rank=None,
            ).to_local()
            source_rows = torch.full((row_count,), -1, dtype=torch.long, device=value.device)
            source_rows[rows.to(value.device)] = torch.arange(rows.numel(), device=value.device)
            source_rows = source_rows[local_rows]
            owned = source_rows >= 0
            rows = torch.arange(local_rows.numel(), device=value.device)[owned]
            column_placements = [
                Replicate() if placement.is_shard() and placement.dim == 0 else placement
                for placement in layout.placements
            ]
            value = distribute_tensor(value, layout.mesh, column_placements, src_data_rank=None).to_local()
            value = value[source_rows[owned]]
        local.index_copy_(0, rows.to(local.device), value)

    def _add_transform(self, prefix: str, transform: Any) -> None:
        """Derive exact source-to-target row indices through the HP inverse."""
        if len(transform.target_patterns) != 1:
            raise ValueError("Unified Qwen3 loading requires one target per HP weight transform")
        target = transform.target_patterns[0]
        target_name = f"{prefix}.{target}" if prefix else target
        self.destinations.pop(target_name, None)
        operations = getattr(transform, "operations", [])
        if not operations:
            if len(transform.source_patterns) != 1:
                raise ValueError("A weight rename must have exactly one source")
            source = transform.source_patterns[0]
            self.destinations[f"{prefix}.{source}" if prefix else source] = _Destination(target_name)
            return
        if len(operations) != 1 or not isinstance(operations[0], (InterleaveQKV, ConcatenateWithSections)):
            raise ValueError(f"Unsupported unified Qwen3 weight conversion at {target_name}: {operations}")
        if isinstance(operations[0], ConcatenateWithSections) and operations[0].dim != 0:
            raise ValueError("Unified Qwen3 weight conversion supports row concatenation only")
        markers = torch.arange(self.shapes[target_name][0], dtype=torch.int64, device="cpu")
        sources = operations[0].reverse_op.convert(
            {target: markers}, [target], transform.source_patterns,
        )
        for source, rows in sources.items():
            source_name = f"{prefix}.{source}" if prefix else source
            self.destinations[source_name] = _Destination(target_name, rows)

    def begin(self) -> None:
        """Begin one full checkpoint or policy publication."""
        if self.active:
            raise RuntimeError("A unified weight publication is already active")
        self.seen.clear()
        self.active = True

    def finish(self) -> None:
        """Reject incomplete logical projections before requests can resume."""
        if not self.active:
            raise RuntimeError("No unified weight publication is active")
        missing = []
        for names in self.required.values():
            # Only exact aliases of an entire parameter may substitute for one another.
            whole_aliases = {name for name in names if self.destinations[name].rows is None
                            and self.destinations[name].region is None}
            if whole_aliases:
                if not self.seen.intersection(whole_aliases):
                    missing.extend(sorted(whole_aliases))
            else:
                missing.extend(sorted(names - self.seen))
        if missing:
            raise ValueError(f"Incomplete unified weight publication; missing logical weights: {missing}")
        self.active = False

    def _load_weight(self, name: str, value: torch.Tensor) -> str | None:
        """Validate and copy one logical projection, retaining publication bookkeeping."""
        if name.endswith(".rotary_emb.inv_freq"):
            return None
        if name in self.seen:
            raise ValueError(f"Duplicate logical weight in unified publication: {name}")
        destination = self.destinations.get(name)
        if destination is None:
            raise ValueError(f"Unknown logical Qwen3 weight: {name}")
        parameter = self.parameters[destination.name]
        expected = self.shapes[destination.name]
        if destination.rows is not None:
            expected = (destination.rows.numel(), *expected[1:])
        if destination.region is not None:
            expected = tuple(reversed(destination.region[1][1:]))
        if tuple(value.shape) != expected:
            raise ValueError(f"Unified weight shape mismatch for {name}: {tuple(value.shape)} != {expected}")
        value = value.to(device=parameter.device, dtype=parameter.dtype)
        aliases = self.required[id(parameter)]
        local = local_target_tensor(parameter)
        if destination.region is not None:
            if destination.local_region is not None:
                local[destination.local_region].copy_(value.transpose(-1, -2).unsqueeze(0))
            self.seen.add(name)
            return destination.name
        if destination.rows is None:
            value = shard_for_target(destination.name, value, parameter)
        if destination.rows is None and self.seen.intersection(aliases):
            if not torch.equal(local, value):
                raise ValueError(f"Conflicting tied Qwen3 weight aliases: {name}")
        elif destination.rows is None:
            local.copy_(value)
        else:
            self._copy_rows(destination.name, destination.rows, value)
        self.seen.add(name)
        return destination.name

    @torch.no_grad()
    def load(self, weights: Iterable[tuple[str, torch.Tensor]]) -> set[str]:
        """Copy logical weights immediately, including independently bucketed Q/K/V."""
        implicit = not self.active
        if implicit:
            self.begin()
        loaded: set[str] = set()
        for name, value in weights:
            destination_name = self._load_weight(name, value)
            if destination_name is not None:
                loaded.add(destination_name)
        if implicit:
            self.finish()
        # vLLM checks actual parameter names, including tied aliases, at initial load.
        loaded_ids = {id(self.parameters[name]) for name in loaded}
        loaded.update(name for name, parameter in self.parameters.items() if id(parameter) in loaded_ids)
        return loaded
